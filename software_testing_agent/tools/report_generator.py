"""QA Test Report Generator Tool for Software Testing Agent.

Generates structured, professional markdown test audit reports and saves them
into the project reports directory.
"""

from datetime import datetime
import os


def generate_qa_report(
    project_name: str,
    test_type: str,
    total_tests: int,
    passed_tests: int,
    failed_tests: int,
    critical_issues: int,
    findings_markdown: str,
    action_items_markdown: str,
    output_filename: str = "qa_audit_report.md",
) -> str:
    """Generates an executive QA test audit report and persists it to disk.

    Args:
        project_name: Name of the application or software module under test.
        test_type: Scope of testing (e.g. 'Unit & Integration', 'REST API', 'Security & Static Analysis', 'Full E2E').
        total_tests: Total number of test cases or endpoints executed/evaluated.
        passed_tests: Number of passed tests.
        failed_tests: Number of failed tests.
        critical_issues: Count of critical or blocker severity issues discovered.
        findings_markdown: Detailed breakdown of test findings, failures, and stack traces.
        action_items_markdown: Concrete developer recommendations and bug fix steps.
        output_filename: Filename for the generated markdown report.

    Returns:
        Confirmation message with the output file path and report summary.
    """
    reports_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), "reports")
    os.makedirs(reports_dir, exist_ok=True)

    target_path = os.path.join(reports_dir, output_filename)
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    pass_rate = round((passed_tests / total_tests * 100), 1) if total_tests > 0 else 0.0

    verdict_badge = "🟢 READY FOR RELEASE" if (failed_tests == 0 and critical_issues == 0) else "🔴 RELEASE BLOCKED"
    if critical_issues == 0 and failed_tests > 0 and pass_rate >= 80:
        verdict_badge = "🟡 CONDITIONAL PASS (Minor Fixes Needed)"

    content = f"""# 📋 QA Software Test Audit Report

**Application:** `{project_name}`  
**Test Scope:** {test_type}  
**Date & Time:** {now_str}  
**Overall Verdict:** {verdict_badge}  

---

## 1. Executive Summary

| Metric | Value | Status |
| :--- | :--- | :--- |
| **Total Test Checks** | {total_tests} | - |
| **Passed** | {passed_tests} | {'✅' if passed_tests == total_tests else '⚠️'} |
| **Failed** | {failed_tests} | {'✅ 0' if failed_tests == 0 else f'❌ {failed_tests}'} |
| **Pass Rate** | {pass_rate}% | {'✅ >90%' if pass_rate >= 90 else '⚠️ Needs Attention'} |
| **Critical / Blocker Issues** | {critical_issues} | {'✅ None' if critical_issues == 0 else f'🚨 {critical_issues} Blocker(s)'} |

---

## 2. Detailed Findings & Failure Diagnoses

{findings_markdown}

---

## 3. Recommended Actions & Patch Guidance

{action_items_markdown}

---
*Report automatically generated by Google ADK Software Testing Agent.*
"""

    try:
        with open(target_path, "w", encoding="utf-8") as f:
            f.write(content)
        return (
            f"✅ QA Test Report successfully written to `{target_path}`!\n\n"
            f"- **Verdict:** {verdict_badge}\n"
            f"- **Pass Rate:** {pass_rate}%\n"
            f"- **Critical Issues:** {critical_issues}\n"
            f"- **Report File:** `{output_filename}`"
        )
    except Exception as e:
        return f"Error saving test report to '{target_path}': {str(e)}"
